// Concatenates The Cardboard Flip's five game scripts into one file, in the
// order the game expects (they are classic scripts sharing the global scope, so
// concatenation preserves behavior). Re-run after copying new sources from the
// tcgscalper repo:  npm run build:flip
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../public/games/thecardboardflip/js");
const ORDER = ["market", "rules", "intro", "game", "progress"];

const parts = ORDER.map(
  (name) => `// ── ${name}.js ──\n${readFileSync(join(dir, `${name}.js`), "utf8").trimEnd()}\n;`
);
const out =
  "// GENERATED by scripts/bundle-cardboard-flip.mjs — do not edit. Edit js/*.js and re-run.\n" +
  parts.join("\n\n") +
  "\n";
writeFileSync(join(dir, "game.bundle.js"), out);
console.log(`wrote js/game.bundle.js (${(out.length / 1024).toFixed(1)} KB) from ${ORDER.join(", ")}`);
